"""Render a :class:`DocPlan` as a whitepaper (.docx).

Page furniture comes from ``assets/templates/vantage-whitepaper.docx`` (generated by
``scripts/build-export-template.py``): three sections whose headers and footers carry the running
title, ``Page N`` and — on every page — the classification marking. This module fills them:

    section 0   cover, then document control / about / handling
    section 1   table of contents (static page numbers after the PDF pass, else a TOC field)
    section 2   the whitepaper body

Headings keep the *dossier's* numbers (§0–§21); Word's automatic numbering is cleared so every
cross-reference in the prose ("see §6.4") still points at the right place. Charts and figures render
where the dossier placed them.
"""

from __future__ import annotations

import datetime as dt
import re
from pathlib import Path

from ..context import RenderContext
from ..dossier import SECTION_ICON
from ..models import (
    Callout,
    ChartBlock,
    Code,
    DocPlan,
    DocSectionPlan,
    DocTreatment,
    Dossier,
    FigureBlock,
    ListBlock,
    Rule,
    Section,
)
from ..models import Paragraph as IRParagraph
from ..models import Table as IRTable
from ..richtext import MARKER_RE, parse_runs, plain
from ..theme import DOC_KIND, HANDLING, SCORE_DISCLAIMER

TEMPLATE = Path(__file__).resolve().parents[1] / "assets" / "templates" / "vantage-whitepaper.docx"

BODY_PT = 10.0
SMALL_PT = 8.5
CAPTION_PT = 9.0

_SOURCE_ID_RE = re.compile(r"S-\d+")
_LINKABLE_RE = re.compile(r"§\s*(?P<sec>\d+(?:\.\d+)*)|\[\s*(?P<src>S-\d+)(?P<rest>[^\]]*)\]")


class DocxRenderer:
    def __init__(self, dossier: Dossier, plan: DocPlan, ctx: RenderContext,
                 template: Path | None = None, toc_pages: dict[str, int] | None = None,
                 links: bool = True, meta: dict | None = None) -> None:
        from docx import Document

        from . import ooxml

        self.ox = ooxml
        self.dossier = dossier
        self.plan = plan
        self.ctx = ctx
        self.meta = meta or {}
        self.P = ctx.theme.palette
        self.T = ctx.theme.type
        self.links = links
        self._section_targets: set[str] = set()
        self._source_targets: set[str] = set()
        if links:
            self._collect_link_targets()
        self.template = Path(template or TEMPLATE)
        if not self.template.exists():
            raise FileNotFoundError(
                f"whitepaper template missing: {self.template}\n"
                f"build it with:  uv run python scripts/build-export-template.py")
        self.doc = Document(str(self.template))
        self._bookmark_id = 1000
        self._figure_no = 0
        self.toc_entries: list[tuple[int, str, str, str]] = []
        self._toc_pages = toc_pages or {}
        self._callout_tone = {
            "verdict": (self.P.accent_tint, self.P.accent, self.P.accent_deep, "Verdict"),
            "warning": ("FBF1E1", self.P.amber, "7A4E0E", "Read this first"),
            "disclaimer": (self.P.surface, self.P.ink_faint, self.P.ink_soft, ""),
            "note": (self.P.surface, self.P.accent, self.P.accent_deep, ""),
        }
        self._retheme_styles()

    # ── setup ────────────────────────────────────────────────────────────────
    def _retheme_styles(self) -> None:
        from docx.shared import RGBColor

        for name, colour, font in (("Heading 1", self.P.accent_deep, self.T.display),
                                   ("Heading 2", self.P.accent_deep, self.T.display),
                                   ("Heading 3", self.P.ink, self.T.body),
                                   ("Title", self.P.ink, self.T.display)):
            try:
                style = self.doc.styles[name]
            except KeyError:
                continue
            style.font.color.rgb = RGBColor.from_string(colour)
            style.font.name = font

    def _collect_link_targets(self) -> None:
        planned = {p.section_id for p in self.plan.sections} | set(self.plan.appendices)
        for root in self.dossier.sections:
            for node in root.walk():
                if node.id in planned or root.id in planned:
                    self._section_targets.add(node.id)
        manifest = self.dossier.find("21.1")
        if manifest is not None and ("21.1" in planned or "21" in planned):
            for node in manifest.walk():
                for block in node.blocks:
                    if isinstance(block, IRTable):
                        for row in block.rows:
                            m = _SOURCE_ID_RE.fullmatch(plain(str(row[0])).strip()) if row else None
                            if m:
                                self._source_targets.add(m.group(0))

    # ── public API ───────────────────────────────────────────────────────────
    def render(self, out_path: Path) -> Path:
        from docx.oxml.ns import qn

        body = self.doc.element.body
        self._breaks = [p for p in body.iterchildren()
                        if p.tag.endswith("}p") and p.find(f"{qn('w:pPr')}/{qn('w:sectPr')}")
                        is not None]
        if len(self._breaks) < 2:
            raise ValueError(f"{self.template.name} is not a three-section whitepaper template")
        self._cover()
        self._front_matter()
        self._body()
        self._toc()
        self._furniture()
        self._set_core_properties()
        out_path.parent.mkdir(parents=True, exist_ok=True)
        self.doc.save(str(out_path))
        return out_path

    def _at(self, break_index: int):
        anchor = self._breaks[break_index]

        def insert(element) -> None:
            anchor.addprevious(element)

        return insert

    def _para(self, insert, text: str = "", style: str | None = None):
        para = self.doc.add_paragraph(style=style)
        if insert is not None:
            self.doc.element.body.remove(para._p)
            insert(para._p)
        if text:
            self._write_runs(para, text)
        return para

    # ── section 0: cover + front matter ──────────────────────────────────────
    def _cover(self) -> None:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Inches, Pt

        ox, P, T = self.ox, self.P, self.T
        insert = self._at(0)
        plan = self.plan

        logo = self.ctx.client_logo
        if logo is not None:
            para = self._para(insert)
            try:
                para.add_run().add_picture(str(logo), height=Inches(0.55))
            except Exception:
                pass
            para.paragraph_format.space_after = Pt(18)
        image = self.ctx.stock(self._cover_query())
        if image is not None:
            para = self._para(insert)
            try:
                para.add_run().add_picture(str(image), width=Inches(6.5))
            except Exception:
                pass
            para.paragraph_format.space_after = Pt(24)
        else:
            spacer = self._para(insert)
            for _ in range(10):
                spacer.add_run().add_break()

        rule = self._para(insert)
        ox.paragraph_border(rule, "top", P.accent, size=24, space=1)
        rule.paragraph_format.space_after = Pt(6)
        title = self._para(insert, "", "Title")
        ox.style_run(title.add_run(plain(plan.client)), font=T.display, size=30, colour=P.ink)
        sub = self._para(insert)
        ox.style_run(sub.add_run(plan.subtitle or DOC_KIND), font=T.display, size=16,
                     colour=P.accent)
        stamp = self._para(insert)
        ox.style_run(stamp.add_run(f"As of {self._as_of_long()}"), font=T.body, size=10,
                     colour=P.ink_faint)
        reliability = self._reliability_line()
        if reliability:
            para = self._para(insert)
            para.alignment = WD_ALIGN_PARAGRAPH.LEFT
            self._write_runs(para, reliability, size=10, colour=P.ink_soft)
        para = self._para(insert)
        para.paragraph_format.space_before = Pt(18)
        ox.style_run(para.add_run(self.ctx.classification), font=T.body, size=10,
                     colour=P.accent_deep, bold=True)
        ox.style_run(para.add_run(f"  ·  {HANDLING}"), font=T.body, size=9, colour=P.ink_faint)
        author = self.ctx.theme.brand_name or plan.author or "Prepared with Vantage"
        para = self._para(insert)
        ox.style_run(para.add_run(author), font=T.body, size=9, colour=P.ink_faint)
        brand = self.ctx.brand_logo
        if brand is not None:
            para = self._para(insert)
            try:
                para.add_run().add_picture(str(brand), height=Inches(0.4))
            except Exception:
                pass
        self._page_break(insert)

    def _cover_query(self) -> str | None:
        from ..dossier import vertical_words

        words = vertical_words(self.dossier)
        return f"{words or 'corporate'} {plain(self.dossier.client)} operations".strip()

    def _reliability_line(self) -> str:
        m = self.meta
        parts = []
        if m.get("overall_confidence") or m.get("eqi") is not None:
            eqi = f" (EQI {m['eqi']:g})" if m.get("eqi") is not None else ""
            parts.append(f"**Overall confidence:** {m.get('overall_confidence') or '—'}{eqi}")
        if m.get("result"):
            counts = " · ".join(f"{m[k]} {k}" for k in ("blockers", "majors", "minors")
                                if m.get(k) is not None)
            parts.append(f"**Verification:** {m['result']}" + (f" ({counts})" if counts else ""))
        return "  ·  ".join(parts)

    def _front_matter(self) -> None:
        insert = self._at(0)
        d, m = self.dossier, self.meta
        self._heading(insert, "Document control", level=1, in_toc=False)
        confidence = " ".join(x for x in (
            d.overall_confidence, f"(EQI {d.eqi:g})" if d.eqi is not None else "") if x)
        rows = [
            ("Client", self.plan.client),
            ("Document", f"{self.plan.subtitle} — {self.plan.title}"),
            ("Version / tier", " · ".join(x for x in (d.version, d.tier) if x) or "—"),
            ("As of", d.as_of or "—"),
            ("Overall confidence", confidence or "—"),
            ("Verification", str(m.get("detail") or m.get("result") or "—")),
            ("Classification", self.ctx.classification),
            ("Generated", dt.date.today().isoformat()),
        ]
        self._grid_table(insert, ["Field", "Value"], [[k, v] for k, v in rows], widths=[2.0, 4.5])
        self._spacer(insert, 10)
        for banner in d.banners:
            label = "Read before use" if banner.tone == "warning" else None
            self._callout_box(insert, banner.text, tone=banner.tone, label=label)
        self._heading(insert, "About this document", level=1, in_toc=False)
        self._para(insert,
                   f"This whitepaper is a formatted export of the {DOC_KIND} produced for "
                   f"**{plain(self.plan.client)}**. Its content is taken entirely from that "
                   f"dossier; no research was performed at export time and no fact was added. "
                   f"Section numbering follows the dossier, so any statement can be traced to its "
                   f"source section and its claim references. Integrity markers such as "
                   f"`[DATA GAP]`, `[ESTIMATED]` and `[INTERNAL REQUIRED]` are carried through as "
                   f"written, and no composite score the dossier marks SUPPRESSED is shown.")
        if self.plan.abstract:
            self._spacer(insert, 6)
            self._callout_box(insert, self.plan.abstract, tone="note", label="Abstract")
        self._spacer(insert, 10)
        self._heading(insert, "Handling", level=1, in_toc=False)
        self._para(insert, f"Classification: **{self.ctx.classification}**. {HANDLING} It "
                           f"contains outside-in account research and internal assessments "
                           f"prepared for pursuit decisions.")
        self._para(insert, SCORE_DISCLAIMER)

    # ── section 1: table of contents ─────────────────────────────────────────
    def _toc(self) -> None:
        from docx.enum.text import WD_TAB_ALIGNMENT, WD_TAB_LEADER
        from docx.shared import Inches, Pt

        ox, P, T = self.ox, self.P, self.T
        insert = self._at(1)
        if not self._toc_pages:
            para = self._para(insert)
            para.paragraph_format.space_after = Pt(6)
            ox.add_field(para, r'TOC \o "1-2" \h \z \u',
                         placeholder="Right-click and choose “Update field” to build the table "
                                     "of contents.")
            return
        right_edge = Inches(self._usable_width_inches(section_index=1))
        for level, number, title, anchor in self.toc_entries:
            if level > 2:
                continue
            para = self._para(insert)
            fmt = para.paragraph_format
            fmt.space_before = Pt(6 if level == 1 else 1)
            fmt.space_after = Pt(0)
            fmt.left_indent = Inches(0.0 if level == 1 else 0.32)
            fmt.tab_stops.add_tab_stop(right_edge, WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
            label = f"{number}  {title}".strip() if number else title
            size = 10.5 if level == 1 else 9.5
            if self.links:
                ox.add_internal_link(para, anchor, label,
                                     P.accent_deep if level == 1 else P.ink, size_pt=size)
            else:
                ox.style_run(para.add_run(label), font=T.display if level == 1 else T.body,
                             size=size, colour=P.accent_deep if level == 1 else P.ink,
                             bold=level == 1)
            para.add_run("\t")
            page = self._toc_pages.get(anchor)
            ox.style_run(para.add_run(str(page) if page else "—"), font=T.body, size=9.5,
                         colour=P.ink_faint)

    # ── section 2: body ──────────────────────────────────────────────────────
    def _body(self) -> None:
        first = True
        for section_plan in self.plan.sections:
            section = self.dossier.find(section_plan.section_id)
            if section is None or section_plan.treatment == DocTreatment.OMIT:
                continue
            # A page break *on the heading*, not a break paragraph before it: a paragraph that
            # lands exactly at a page end would otherwise leave a blank page.
            self._break_next = bool(section_plan.page_break_before and not first)
            first = False
            self._render_section(section, section_plan, depth=1)
        self._appendices()

    def _render_section(self, section: Section, plan: DocSectionPlan | None, depth: int,
                        treatment: DocTreatment | None = None) -> None:
        from docx.shared import Pt

        heading = (plan.heading_override if plan else None) or section.title
        self._heading(None, heading, level=min(depth, 3), number=section.number,
                      bookmark=f"sec_{section.id}",
                      icon=SECTION_ICON.get(section.id) if depth == 1 else None)
        if plan and plan.lead:
            para = self.doc.add_paragraph()
            para.paragraph_format.space_after = Pt(8)
            self._write_runs(para, plan.lead, italic=True, colour=self.P.ink_soft)
        treatment = plan.treatment if plan else (treatment or DocTreatment.VERBATIM)
        if treatment == DocTreatment.SUMMARY and plan and plan.summary:
            for chunk in plan.summary.split("\n\n"):
                self._write_runs(self.doc.add_paragraph(), chunk)
        else:
            self._render_blocks(section, condense=treatment == DocTreatment.CONDENSE)
        if plan:
            for callout in plan.callouts:
                self._callout_box(None, callout.text, tone=callout.tone)
            for chart in plan.charts:
                self._chart(chart)
        if treatment == DocTreatment.SUMMARY and plan and plan.summary:
            return
        child_treatment = treatment if treatment == DocTreatment.CONDENSE else None
        for child in section.children:
            self._render_section(child, None, depth + 1, child_treatment)

    def _render_blocks(self, section: Section, condense: bool = False) -> None:
        prose_budget = 2 if condense else None
        prose_seen = 0
        for block in section.blocks:
            if isinstance(block, IRParagraph):
                # Condensing trims prose — never a paragraph that carries an integrity marker.
                keep = MARKER_RE.search(block.text) is not None
                if prose_budget is not None and prose_seen >= prose_budget and not keep:
                    continue
                prose_seen += 1
                for chunk in block.text.split("\n\n"):
                    if chunk.strip():
                        self._write_runs(self.doc.add_paragraph(), chunk)
            elif isinstance(block, IRTable):
                self._ir_table(block)
            elif isinstance(block, ListBlock):
                self._list(block)
            elif isinstance(block, Callout):
                self._callout_box(None, block.text, tone=block.tone)
            elif isinstance(block, ChartBlock):
                self._chart(block.spec)
            elif isinstance(block, FigureBlock):
                self._figure(block.spec)
            elif isinstance(block, Code):
                self._code(block)
            elif isinstance(block, Rule):
                continue

    def _appendices(self) -> None:
        if self.plan.appendix_policy == "none":
            return
        if self.plan.appendix_policy == "all":
            chosen = [s for s in self.dossier.sections if s.id == "21"]
        else:
            chosen = [n for a in self.plan.appendices if (n := self.dossier.find(a)) is not None]
        planned = {p.section_id for p in self.plan.sections}
        chosen = [s for s in chosen if s.id not in planned]
        if not chosen:
            return
        self._break_next = True
        self._heading(None, "Appendices", level=1, bookmark="sec_appendices",
                      icon=SECTION_ICON.get("21"))
        self._para(None, "The registers below are reproduced from §21 of the dossier so the "
                         "sources, verification findings and gaps referenced in the body can be "
                         "resolved without leaving this document.")
        for section in chosen:
            self._render_section(section, None, depth=2)

    # ── content primitives ───────────────────────────────────────────────────
    def _heading(self, insert, text: str, level: int, *, number: str = "",
                 bookmark: str | None = None, in_toc: bool = True, icon: str | None = None):
        from docx.shared import Inches

        ox = self.ox
        style = f"Heading {min(level, 3)}"
        para = self.doc.add_paragraph(style=style) if insert is None else self._para(
            insert, style=style)
        self._clear_numbering(para)
        if insert is None and getattr(self, "_break_next", False):
            para.paragraph_format.page_break_before = True
            self._break_next = False
        title = plain(text)
        label = number.rstrip(".") if number else ""
        if icon:
            path = self.ctx.icon_png(icon, self.P.accent)
            if path is not None:
                try:
                    para.add_run().add_picture(str(path), height=Inches(0.24))
                    para.add_run("  ")
                except Exception:
                    pass
        if label:
            ox.style_run(para.add_run(f"{label}  "), bold=True)
        para.add_run(title)
        ox.keep_with_next(para)
        if bookmark:
            self._bookmark_id += 1
            ox.add_bookmark(para, bookmark, self._bookmark_id)
            if in_toc:
                self.toc_entries.append((min(level, 3), label, title, bookmark))
        return para

    def _clear_numbering(self, para) -> None:
        from docx.oxml.ns import qn
        from docx.oxml.parser import OxmlElement

        p_pr = para._p.get_or_add_pPr()
        for existing in p_pr.findall(qn("w:numPr")):
            p_pr.remove(existing)
        num_pr = OxmlElement("w:numPr")
        for tag, value in (("w:ilvl", "0"), ("w:numId", "0")):
            node = OxmlElement(tag)
            node.set(qn("w:val"), value)
            num_pr.append(node)
        p_pr.insert(0, num_pr)

    def _write_runs(self, para, text: str, *, italic: bool = False, colour: str | None = None,
                    size: float = BODY_PT):
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        ox, P, T = self.ox, self.P, self.T
        if para.alignment is None:
            para.alignment = WD_ALIGN_PARAGRAPH.LEFT
        for piece in parse_runs(text):
            if self.links and not piece.code and _LINKABLE_RE.search(piece.text):
                self._write_linked(para, piece, size, colour, italic)
                continue
            run = para.add_run(piece.text)
            if piece.code:
                marker = MARKER_RE.search(piece.text) is not None
                ox.style_run(run, font=T.mono, size=size - 1.5,
                             colour=P.red if marker else P.accent_deep,
                             bold=piece.bold or marker, italic=piece.italic or italic)
            else:
                ox.style_run(run, font=T.body, size=size, colour=colour, bold=piece.bold,
                             italic=piece.italic or italic, strike=piece.strike or None)
        return para

    def _write_linked(self, para, piece, size: float, colour: str | None, italic: bool) -> None:
        ox, T = self.ox, self.T

        def plain_run(text: str) -> None:
            ox.style_run(para.add_run(text), font=T.body, size=size, colour=colour,
                         bold=piece.bold, italic=piece.italic or italic,
                         strike=piece.strike or None)

        pos = 0
        for match in _LINKABLE_RE.finditer(piece.text):
            if piece.text[pos:match.start()]:
                plain_run(piece.text[pos:match.start()])
            token = match.group(0)
            anchor = None
            if match.group("sec"):
                sid = match.group("sec")
                anchor = f"sec_{sid}" if sid in self._section_targets else None
            elif match.group("src"):
                sid = match.group("src")
                anchor = f"src_{sid}" if sid in self._source_targets else None
            if anchor:
                ox.add_internal_link(para, anchor, token, self.P.accent_deep, size_pt=size)
            else:
                plain_run(token)
            pos = match.end()
        if piece.text[pos:]:
            plain_run(piece.text[pos:])

    def _spacer(self, insert=None, points: int = 8) -> None:
        from docx.shared import Pt

        para = self._para(insert)
        para.paragraph_format.space_after = Pt(points)
        para.paragraph_format.space_before = Pt(0)

    def _page_break(self, insert) -> None:
        from docx.enum.text import WD_BREAK

        self._para(insert).add_run().add_break(WD_BREAK.PAGE)

    def _list(self, block: ListBlock) -> None:
        from docx.shared import Inches, Pt

        for item in block.items:
            style = "List Number" if block.ordered else "List Bullet"
            try:
                para = self.doc.add_paragraph(style=style)
            except KeyError:
                para = self.doc.add_paragraph(style="List Paragraph")
            para.paragraph_format.left_indent = Inches(0.25 + 0.25 * item.level)
            para.paragraph_format.space_after = Pt(2)
            self._write_runs(para, item.text)

    def _code(self, block: Code) -> None:
        from docx.shared import Inches

        para = self.doc.add_paragraph()
        para.paragraph_format.left_indent = Inches(0.25)
        self.ox.paragraph_shading(para, self.P.surface)
        self.ox.style_run(para.add_run(block.text), font=self.T.mono, size=SMALL_PT,
                          colour=self.P.ink)

    def _caption(self, text: str, kind: str = "Figure") -> None:
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        self._figure_no += 1
        para = self.doc.add_paragraph(style="Caption")
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.ox.style_run(para.add_run(f"{kind} {self._figure_no}. {plain(text)}"),
                          font=self.T.body, size=CAPTION_PT, italic=True, colour=self.P.ink_soft)

    # ── tables ───────────────────────────────────────────────────────────────
    def _ir_table(self, block: IRTable) -> None:
        if not block.header and not block.rows:
            return
        self._grid_table(None, block.header, block.rows, aligns=block.aligns)
        if block.caption:
            self._caption(block.caption, "Table")
        self._spacer(points=6)

    def _grid_table(self, insert, header: list[str], rows: list[list[str]],
                    widths: list[float] | None = None, aligns: list[str] | None = None):
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Inches, Pt

        ox, P, T = self.ox, self.P, self.T
        cols = max(len(header), max((len(r) for r in rows), default=0))
        if cols == 0:
            return None
        table = self.doc.add_table(rows=0, cols=cols)
        table.style = "Table Grid"
        table.autofit = False
        if insert is not None:
            self.doc.element.body.remove(table._tbl)
            insert(table._tbl)
        usable = self._usable_width_inches()
        widths = ([w * usable / sum(widths) for w in widths] if widths
                  else self._auto_widths(header, rows, usable))
        body_pt = SMALL_PT if cols <= 5 else 7.5 if cols <= 8 else 6.5
        head_pt = min(body_pt, SMALL_PT)
        if header:
            cells = table.add_row().cells
            for idx, text in enumerate(header[:cols]):
                c = cells[idx]
                ox.shade(c, P.accent)
                ox.cell_margins(c, top=60, start=90, bottom=60, end=90)
                ox.cell_valign(c)
                para = c.paragraphs[0]
                para.alignment = WD_ALIGN_PARAGRAPH.LEFT
                para.paragraph_format.space_after = Pt(0)
                ox.style_run(para.add_run(plain(text)), font=T.body, size=head_pt,
                             colour="FFFFFF", bold=True)
            ox.repeat_header_row(table.rows[0])
            ox.prevent_row_split(table.rows[0])
        for row_index, row in enumerate(rows):
            cells = table.add_row().cells
            for col_index in range(cols):
                c = cells[col_index]
                text = row[col_index] if col_index < len(row) else ""
                if row_index % 2 == 1:
                    ox.shade(c, P.surface)
                ox.cell_margins(c, top=50, start=90, bottom=50, end=90)
                ox.cell_borders(c, top=None if row_index else (P.accent, 8),
                                bottom=(P.rule, 4), left=None, right=None)
                para = c.paragraphs[0]
                if self.links and col_index == 0 and (
                        sid := _SOURCE_ID_RE.fullmatch(plain(str(text)).strip())):
                    self._bookmark_id += 1
                    ox.add_bookmark(para, f"src_{sid.group(0)}", self._bookmark_id)
                para.paragraph_format.space_after = Pt(0)
                if aligns and col_index < len(aligns):
                    para.alignment = {"right": WD_ALIGN_PARAGRAPH.RIGHT,
                                      "center": WD_ALIGN_PARAGRAPH.CENTER}.get(
                        aligns[col_index], WD_ALIGN_PARAGRAPH.LEFT)
                self._write_runs(para, text, size=body_pt)
        for idx, width in enumerate(widths[:cols]):
            table.columns[idx].width = Inches(width)
        for row in table.rows:
            for idx, c in enumerate(row.cells):
                if idx < len(widths):
                    ox.set_cell_width(c, int(widths[idx] * 1440))
        ox.table_layout_fixed(table)
        return table

    def _auto_widths(self, header: list[str], rows: list[list[str]], usable: float) -> list[float]:
        cols = max(len(header), max((len(r) for r in rows), default=0))
        if cols == 0:
            return []
        weights: list[float] = []
        for col in range(cols):
            samples = sorted(len(plain(r[col])) for r in rows if col < len(r))
            head_len = len(plain(header[col])) if col < len(header) else 0
            typical = samples[int(len(samples) * 0.75)] if samples else 0
            weights.append(max(4.0, min(float(max(typical, head_len * 0.8)), 200.0)))
        total = sum(weights) or 1.0
        widths = [usable * w / total for w in weights]
        floor = min(0.62, usable / (cols * 2.2))
        deficit = sum(floor - w for w in widths if w < floor)
        widths = [max(w, floor) for w in widths]
        if deficit > 0:
            surplus = sum(w - floor for w in widths if w > floor) or 1.0
            widths = [w - (w - floor) / surplus * deficit if w > floor else w for w in widths]
        scale = usable / sum(widths)
        return [w * scale for w in widths]

    def _usable_width_inches(self, section_index: int = -1) -> float:
        from docx.shared import Emu

        section = self.doc.sections[section_index]
        return Emu(section.page_width - section.left_margin - section.right_margin).inches

    # ── callouts ─────────────────────────────────────────────────────────────
    def _callout_box(self, insert, text: str, tone: str = "note", label: str | None = None) -> None:
        from docx.shared import Pt

        ox, T = self.ox, self.T
        fill, bar, label_colour, default_label = self._callout_tone.get(
            tone, self._callout_tone["note"])
        heading = label if label is not None else default_label
        if tone == "verdict" and re.match(r"^\*\*Verdict", text):
            heading = ""   # the dossier's own bold "Verdict." label leads the text
        table = self.doc.add_table(rows=1, cols=1)
        table.autofit = False
        if insert is not None:
            self.doc.element.body.remove(table._tbl)
            insert(table._tbl)
        c = table.cell(0, 0)
        ox.shade(c, fill)
        ox.cell_margins(c, top=120, start=160, bottom=120, end=160)
        ox.cell_borders(c, left=(bar, 24), top=None, bottom=None, right=None)
        ox.set_cell_width(c, int(self._usable_width_inches() * 1440))
        ox.table_layout_fixed(table)
        para = c.paragraphs[0]
        para.paragraph_format.space_after = Pt(0)
        if heading:
            ox.style_run(para.add_run(heading), font=T.display, size=BODY_PT,
                         colour=label_colour, bold=True)
            para = c.add_paragraph()
            para.paragraph_format.space_after = Pt(0)
        chunks = [ch for ch in text.split("\n\n") if ch.strip()]
        for index, chunk in enumerate(chunks):
            target = para if index == 0 else c.add_paragraph()
            target.paragraph_format.space_after = Pt(0 if index == len(chunks) - 1 else 4)
            self._write_runs(target, chunk, size=BODY_PT - 0.5, colour=self.P.ink_soft,
                             italic=tone == "disclaimer")
        self._spacer(insert, points=8)

    # ── visuals ──────────────────────────────────────────────────────────────
    def _chart(self, spec) -> None:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Inches

        width = self._usable_width_inches() * 0.9
        image = self.ctx.charts.png(spec, width_in=width)
        if image is None:
            return
        para = self.doc.add_paragraph()
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        para.add_run().add_picture(str(image), width=Inches(width))
        self.ox.keep_with_next(para)
        label = f"{spec.id} — {spec.title}" if spec.id else spec.title
        self._caption(f"{label}" + (f" ({spec.note})" if spec.note else ""), "Figure")

    def _figure(self, spec) -> None:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Inches

        from ..visuals import figure_table

        art = self.ctx.figures.render(spec)
        if art is not None and art.png is not None:
            width = self._usable_width_inches() * 0.95
            try:
                from PIL import Image

                with Image.open(art.png) as img:
                    ratio = img.height / max(img.width, 1)
                width = min(width, 8.0 / max(ratio, 0.01))   # keep tall diagrams on one page
            except Exception:
                pass
            para = self.doc.add_paragraph()
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            para.add_run().add_picture(str(art.png), width=Inches(width))
            self.ox.keep_with_next(para)
            self._caption(spec.caption(), "Figure")
            return
        table = figure_table(spec)
        if table is not None:
            self._caption(spec.caption(), "Figure")
            self._grid_table(None, table.header, table.rows)
            self._spacer(points=6)

    # ── furniture + metadata ─────────────────────────────────────────────────
    def _furniture(self) -> None:
        values = {"{{DOC_TITLE}}": self._running_title(),
                  "{{CLASSIFICATION}}": self.ctx.classification}
        seen: set[int] = set()
        for section in self.doc.sections:
            for part in (section.header, section.footer, section.first_page_header,
                         section.first_page_footer, section.even_page_header,
                         section.even_page_footer):
                if id(part._element) in seen:
                    continue
                seen.add(id(part._element))
                for para in part.paragraphs:
                    for run in para.runs:
                        for key, value in values.items():
                            if key in run.text:
                                run.text = run.text.replace(key, value)

    def _set_core_properties(self) -> None:
        props = self.doc.core_properties
        props.title = self._running_title()
        props.subject = f"{plain(self.plan.client)} — {self.plan.subtitle}"
        props.author = self.ctx.theme.brand_name or "Vantage"
        props.category = self.ctx.classification
        props.comments = f"{self.ctx.classification}. {HANDLING}"
        props.keywords = f"{self.ctx.classification}; Vantage dossier; internal"

    def _running_title(self) -> str:
        title = re.sub(r"\s+", " ", plain(self.plan.title or self.plan.client)).strip()
        return title if len(title) <= 48 else title[:47].rstrip(" ,.;—–-") + "…"

    def _as_of_long(self) -> str:
        raw = self.plan.as_of or self.dossier.as_of or dt.date.today().isoformat()
        try:
            return dt.date.fromisoformat(raw).strftime("%B %-d, %Y")
        except ValueError:
            return raw
